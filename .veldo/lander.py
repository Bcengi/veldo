#!/usr/bin/env python3
"""veldo lander: land a completed build to the trunk, serialized across the fleet.

When a worker finishes building a spec on its own branch, the built work has to reach the
trunk without colliding with the other workers landing at the same moment. The lander makes
that safe with three guarantees:

  1. SERIALIZED. A single fleet-wide land lock (a well-known unit in the claim ledger,
     WARP-0701) means only one land runs at a time. The lock is acquired by waiting, held
     with a heartbeat so a long land never looks dead, and released in a finally so a crash
     never wedges the trunk. A fast-forward-only push is the correctness backstop: even if
     the lock were ever stolen from a stalled holder, a stale push simply fails rather than
     clobbering the trunk.

  2. MERGE, NOT REWRITE. The build is MERGED (not cherry-picked), so the build's
     implementation and evidence commits keep their shas - which is what keeps the proof and
     verdict, both digest-bound to the implementation commit, valid after landing. The trunk
     may have advanced since the build started (a prior land); the merge replays the build onto
     it, union-resolving the known shared APPEND-ONLY files (the selftest, the capability
     catalogs, the event log) and regenerating the spec index, while a conflict in any OTHER
     file is a real conflict that the build must resolve itself - the lander rejects it rather
     than guessing.

  3. A DISPOSABLE CANDIDATE, NEVER THE CALLER'S TRUNK (VELDO-0056, PLAN-0019 W41, R48, R76).
     Every land builds its candidate in a dedicated detached workspace: a new repository
     (git init with no template) whose object store borrows the caller repository's objects
     through Git alternates, as VELDO-0042's worker clones do, so it shares no refs, no index,
     no HEAD, no configuration and no worktree link with the caller. Nothing checks out, moves
     or even fetches into the caller's trunk, so another worktree holding the trunk, or a trunk
     with any name, changes nothing. Construction, in order (sync_main, then reconcile):

       the watermark  the published trunk tip, fetched once into the workspace (or, with push
                      disabled, the caller's local trunk tip, read and never written). Every
                      later step uses that exact commit: it is the candidate's fixed input.
       implementation the commit the unit's proof names (proof/<unit>/manifest.json at the
                      evidence commit), required to exist and to be an ancestor of the evidence
                      commit, merged first with --no-ff.
       evidence       the built commit the build ref names, merged second, so the candidate
                      keeps distinct implementation and evidence ancestry.
       projections    each derived file (specs/index.md) regenerated by the candidate's own
                      generator from the merged tree, and committed. The candidate is then
                      required clean.

     Every Git operation on that path goes through one checked step, so a failed fetch, merge,
     object lookup, index write or commit refuses the candidate by name (the failing operation
     is in the refusal), and missing required evidence refuses it before anything is merged.
     The gate runs in the candidate and is green only on exit 0 with a terminal GREEN line for
     the candidate commit. finalize then asks the policy about that exact candidate. For a
     factory land it is the authority's CandidatePolicy, installed code outside the candidate
     (R50): the accepted proof (VELDO-0050), the review obligations (VELDO-0049) and the
     publication decision over the candidate workspace (VELDO-0052). A pre-factory land with no
     authority policy wired asks the repository policy (policy_check.py) at the candidate, over
     exactly watermark..candidate. Only after the policy accepts does anything move: the exact
     candidate commit is pushed, fast-forward only. Every refusal leaves the caller's
     refs, HEAD, index and working bytes, and the remote trunk, exactly as they were, and the
     workspace is removed at the end of every land. Local trunk synchronization, exact-tip
     publication and the completion receipt are VELDO-0057's; a kill or restart during
     construction and competing landers are Release 2.

The lander's control logic (lock, serialize, stage order, abort-and-release, ff-push guard)
is mechanical and gate-tested over a fake LandOps with no real git; the real git steps live in
GitLandOps. Pure stdlib; Unix-only via the claim ledger."""

