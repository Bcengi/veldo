import { SCREENS, expect, signIn, test } from './fixtures'

test('smoke: sign in and look at the screens', async ({ page, factory, guarded }) => {
  const state = await factory.state()
  await page.setViewportSize({ width: 1280, height: 860 })
  await page.goto(factory.origin + '/runs')
  await page.screenshot({ path: `${SCREENS}/smoke-signin.png` })
  await signIn(page, factory)
  await page.goto(factory.origin + '/runs')
  await expect(page.getByTestId('runs')).toBeVisible()
  await page.screenshot({ path: `${SCREENS}/smoke-runs.png` })
  await page.goto(factory.origin + '/runs/' + state.dispatches.done)
  await expect(page.getByTestId('lines')).toBeVisible()
  await page.waitForTimeout(1500)
  await page.screenshot({ path: `${SCREENS}/smoke-run.png` })
  await page.goto(factory.origin + '/decisions/' + state.requests.de1)
  await expect(page.getByTestId('decision')).toBeVisible()
  await page.screenshot({ path: `${SCREENS}/smoke-decision.png` })
  await page.setViewportSize({ width: 390, height: 844 })
  await page.screenshot({ path: `${SCREENS}/smoke-decision-phone.png` })
  console.log('violations', await guarded.violations())
})

test('smoke: phone run and edit diff', async ({ page, factory, guarded }) => {
  const state = await factory.state()
  await page.setViewportSize({ width: 390, height: 844 })
  await signIn(page, factory)
  await page.goto(factory.origin + '/runs')
  await page.screenshot({ path: `${SCREENS}/smoke-runs-phone.png` })
  await page.goto(factory.origin + '/runs/' + state.dispatches.done)
  await expect(page.getByTestId('lines')).toBeVisible()
  await page.locator('[data-seq="7"]').scrollIntoViewIfNeeded()
  await page.waitForTimeout(2000)
  await page.screenshot({ path: `${SCREENS}/smoke-run-phone.png` })
  await page.setViewportSize({ width: 1280, height: 860 })
  await page.evaluate(() => document.documentElement.setAttribute('data-theme', 'dark'))
  await page.locator('[data-seq="7"]').scrollIntoViewIfNeeded()
  await page.waitForTimeout(1500)
  await page.screenshot({ path: `${SCREENS}/smoke-run-dark.png` })
  console.log('violations', await guarded.violations())
})
